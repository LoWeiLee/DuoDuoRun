/** 給定 n，回傳 14 個 α 對應的臨界 D（n > 1600 走漸近式，否則在 n 網格上線性內插） */
function lillieforsCritvals(n) {
  const nAlpha = LILLIEFORS_ALPHA.length
  const out = new Array(nAlpha)
  const maxSize = LILLIEFORS_SIZE[LILLIEFORS_SIZE.length - 1]
  if (n > maxSize) {
    const l = Math.log(n)
    for (let j = 0; j < nAlpha; j++) {
      const [b, c0, c1] = LILLIEFORS_ASYMP[j]
      out[j] = Math.exp(b + c0 * l + c1 * l * l)
    }
    return out
  }
  let hi = 1
  while (hi < LILLIEFORS_SIZE.length - 1 && LILLIEFORS_SIZE[hi] < n) hi++
  const lo = hi - 1
  const nLo = LILLIEFORS_SIZE[lo]
  const nHi = LILLIEFORS_SIZE[hi]
  const w = nHi === nLo ? 0 : (n - nLo) / (nHi - nLo)
  for (let j = 0; j < nAlpha; j++) {
    out[j] = LILLIEFORS_CRIT[lo][j] + w * (LILLIEFORS_CRIT[hi][j] - LILLIEFORS_CRIT[lo][j])
  }
  return out
}

/** 臨界值表法：對 D 在臨界值上線性內插出 p（statsmodels TableDist.prob） */
function lillieforsTableProb(D, n) {
  // 臨界值隨 α 遞增而遞減（statsmodels 的 signcrit = -1）⇒ 兩邊同時反轉，讓臨界值遞增
  const critv = lillieforsCritvals(n).reverse()
  const alpha = LILLIEFORS_ALPHA.slice().reverse()
  const last = critv.length - 1
  if (D < critv[0]) return alpha[0]
  if (D > critv[last]) return alpha[last]
  let i = 1
  while (i < last && critv[i] < D) i++
  const w = (D - critv[i - 1]) / (critv[i] - critv[i - 1])
  return alpha[i - 1] + w * (alpha[i] - alpha[i - 1])
}

/**
 * Lilliefors p 值（statsmodels `pvalmethod='approx'` 的忠實移植）
 *
 * @param {number} D Lilliefors／KS 統計量
 * @param {number} n 樣本數（≥ 4）
 */
export function lillieforsPValue(D, n) {
  if (!Number.isFinite(D) || D < 0 || !Number.isFinite(n) || n < 4) return NaN
  // ── DW 近似：n > 100 必須先重標定，否則公式被用在定義域外（R60）──
  let d = D
  let m = n
  if (m > 100) {
    d = D * Math.pow(n / 100, 0.49)
    m = 100
  }
  const t = m + 2.78019
  let p = Math.exp(
    -7.01256 * d * d * t +
      2.99587 * d * Math.sqrt(t) -
      0.122119 +
      0.974598 / Math.sqrt(m) +
      1.67997 / m
  )
  // ── DW 只在 p < 0.1 有效，超出改走臨界值表（R60）──
  if (p > 0.1) p = lillieforsTableProb(D, n)
  return Math.max(0, Math.min(1, p))
}
